
-- 1. Venues
CREATE TABLE venues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    city VARCHAR(100) NOT NULL,
    address TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Physical seats belonging to a venue
CREATE TABLE seats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id BIGINT NOT NULL REFERENCES venues(id),
    row_label VARCHAR(10) NOT NULL,
    seat_number INT NOT NULL,
    seat_type VARCHAR(30) NOT NULL DEFAULT 'REGULAR',

    CONSTRAINT uq_venue_seat
        UNIQUE (venue_id, row_label, seat_number),

    CONSTRAINT chk_seat_number
        CHECK (seat_number > 0),

    CONSTRAINT uq_seat_venue_id
        UNIQUE (id, venue_id)
);

-- 3. Scheduled performances of an event
CREATE TABLE event_shows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id),
    venue_id BIGINT NOT NULL REFERENCES venues(id),
    start_time TIMESTAMPTZ NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'SCHEDULED',

    CONSTRAINT chk_show_status
        CHECK (status IN (
            'SCHEDULED', 'CANCELLED', 'COMPLETED'
        )),

    CONSTRAINT uq_show_venue_id
        UNIQUE (id, venue_id)
);

-- 4. Seat inventory for each individual show
CREATE TABLE show_seats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    show_id BIGINT NOT NULL,
    venue_id BIGINT NOT NULL,
    seat_id BIGINT NOT NULL,
    price NUMERIC(10,2) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE',

    CONSTRAINT fk_show_seat_show
        FOREIGN KEY (show_id, venue_id)
        REFERENCES event_shows(id, venue_id),

    CONSTRAINT fk_show_seat_seat
        FOREIGN KEY (seat_id, venue_id)
        REFERENCES seats(id, venue_id),

    CONSTRAINT uq_show_seat
        UNIQUE (show_id, seat_id),

    CONSTRAINT chk_seat_price
        CHECK (price >= 0),

    CONSTRAINT chk_inventory_status
        CHECK (status IN (
            'AVAILABLE', 'HELD', 'BOOKED', 'BLOCKED'
        ))
);

-- Indexes for frequent queries
CREATE INDEX idx_seats_venue
    ON seats(venue_id);

CREATE INDEX idx_shows_event
    ON event_shows(event_id);

CREATE INDEX idx_shows_start_time
    ON event_shows(start_time);

CREATE INDEX idx_show_seats_show_status
    ON show_seats(show_id, status);
